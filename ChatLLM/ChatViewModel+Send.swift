//
//  ChatViewModel+Send.swift
//  ChatLLM
//
//  Starting a user turn: appending the user message and the assistant
//  placeholder, then streaming the reply.
//

import Foundation
import os

extension ChatViewModel {

    // MARK: - Chat flow

    func send(
        userText: String,
        forceSearch: Bool = false,
        disableToolCalls: Bool = false,
        regenerateTitle: Bool = false,
        editedUserMessageID: UUID? = nil
    ) async {
        _ = await trySend(
            userText: userText,
            forceSearch: forceSearch,
            disableToolCalls: disableToolCalls,
            regenerateTitle: regenerateTitle,
            editedUserMessageID: editedUserMessageID
        )
    }

    /// `send`, reporting whether the message was accepted. Returns false when it was not
    /// sent (another reply or a regeneration is still running, or the chat was closed), so
    /// a composer that has already cleared its text can give it back to the user.
    func trySend(
        userText: String,
        forceSearch: Bool = false,
        disableToolCalls: Bool = false,
        regenerateTitle: Bool = false,
        editedUserMessageID: UUID? = nil
    ) async -> Bool {
        let trimmed = userText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return false }

        guard beginUserTurn() else { return false }
        return await runTurn { generationID in
            let shouldUseReasoning = self.resolvedReasoningMode(for: trimmed)

            guard self.isGenerationActive(generationID) else { return }

            guard let turn = self.prepareUserMessageForSend(
                trimmed,
                forceAutoNaming: regenerateTitle,
                replacingMessageID: editedUserMessageID
            ) else { return }
            // Editing only the text of an image message keeps its image, and image
            // turns are answered without web search (see `sendWithImage`).
            let answersImage = !turn.message.attachments.isEmpty
            let searches = forceSearch && !answersImage
            let assistantMsg = self.appendAssistantPlaceholder(
                isReasoningMode: shouldUseReasoning,
                searchQuery: searches ? trimmed : nil,
                requiresWebSearch: searches
            )

            guard self.isGenerationActive(generationID) else { return }

            let searchInstruction = searches
                ? "You must call the webSearch tool before answering. Search for current information about this request first, then answer using the tool results."
                : nil
            await self.streamAssistant(
                into: assistantMsg,
                basedOnHistoryUpTo: assistantMsg.order,
                additionalUserInstruction: searchInstruction,
                disableWebSearch: disableToolCalls || answersImage,
                generationID: generationID
            )

            guard self.isGenerationActive(generationID) else { return }
            self.scheduleAutoNamingIfNeeded(turn.needsAutoNaming)
        }
    }

    /// Checks shared by text and image sends before a turn starts.
    internal func beginUserTurn() -> Bool {
        guard !isRegenerating else {
            logger.notice("Send refused: a regeneration is in progress")
            return false
        }
        // A message sent while a menu's delayed regeneration is still waiting
        // supersedes it; otherwise the regeneration would delete this new turn.
        scheduledRegenerationTask?.cancel()
        scheduledRegenerationTask = nil
        return true
    }

    // MARK: - Turn Messages

    /// Any turn may name the chat while it still has the default title: the first
    /// reply can be stopped before naming runs, and vague openers defer naming.
    private func needsAutoNaming(force: Bool) -> Bool {
        force || (
            AppLanguage.isDefaultConversationTitle(conversation.title) &&
            !conversation.hasAutoGeneratedTitle
        )
    }

    internal func resolvedReasoningMode(for prompt: String) -> Bool {
        shouldUseReasoningForPrompt(prompt)
    }

    /// A reply without a preceding user message follows the same rule, with no
    /// prompt for smart reasoning to judge.
    internal func resolvedReasoningMode(for userMessage: Message?) -> Bool {
        shouldUseReasoningForPrompt(userMessage?.text)
    }

    internal func appendUserMessage(
        _ text: String,
        forceAutoNaming: Bool = false
    ) -> (message: Message, needsAutoNaming: Bool) {
        let userMsg = Message(
            role: .user,
            text: text,
            order: nextOrder,
            conversation: conversation,
            isFinal: true
        )
        conversation.messages.append(userMsg)

        let needsAutoNaming = needsAutoNaming(force: forceAutoNaming)

        return (userMsg, needsAutoNaming)
    }

    internal func prepareUserMessageForSend(
        _ text: String,
        forceAutoNaming: Bool = false,
        replacingMessageID: UUID? = nil
    ) -> (message: Message, needsAutoNaming: Bool)? {
        guard let replacingMessageID else {
            return appendUserMessage(text, forceAutoNaming: forceAutoNaming)
        }

        guard let userMessage = conversation.messages.first(where: {
            $0.id == replacingMessageID && $0.role == .user
        }) else {
            logger.warning("Edited user message disappeared before send")
            return nil
        }

        userMessage.text = text
        userMessage.isFinal = true

        return (userMessage, needsAutoNaming(force: forceAutoNaming))
    }

    internal func appendAssistantPlaceholder(
        isReasoningMode: Bool,
        searchQuery: String? = nil,
        requiresWebSearch: Bool = false
    ) -> Message {
        let assistantMsg = Message(
            role: .assistant,
            text: "",
            order: nextOrder,
            conversation: conversation,
            isFinal: false,
            isReasoningMode: isReasoningMode,
            searchQuery: searchQuery,
            requiresWebSearch: requiresWebSearch
        )
        conversation.messages.append(assistantMsg)
        conversation.lastUpdated = Date()
        immediateSave()
        return assistantMsg
    }
}
